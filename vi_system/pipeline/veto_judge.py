# ==================================================================== 启发式
def _heuristic(industry: str, rule: str, rule_desc: str, value) -> str:
    ind = str(industry)

    def v(x=value):
        try:
            return float(x)
        except (TypeError, ValueError):
            return float("nan")

    # --- Beneish M-Score：高成长/应收/金融 误报为主
    if rule == "beneish_m_score":
        m = v()
        if ind in ("电子", "通信", "计算机"):
            return f"⚠️ 误报——半导体/AI/光模块营收高增长拉高 SGI/TATA，M={m:.2f} 属高成长误报，建议复核现金流质量而非直接否掉"
        if ind == "电力设备":
            return f"⚠️ 误报——光伏/锂电应收账款激增(DSRI)或营收高增(SGI)拉高 M，属行业性误报，建议看回款与存货"
        if ind == "食品饮料":
            return f"⚠️ 误报——白酒/食品经销商预收与淡旺季结构拉高 M，商业模式使然，非财务造假"
        if ind in ("医药生物",):
            return f"🔍 需复核——医药研发资本化/应收账款需逐项核实，M={m:.2f} 偏高不一定造假"
        if ind in ("银行", "非银金融"):
            return f"⚠️ 误报——金融企业 Beneish 分量口径不适用，M 无实业可比性"
        if ind in ("有色金属", "钢铁", "基础化工", "石油石化", "煤炭", "农林牧渔"):
            return f"🔍 需复核——周期行业利润与应收/存货同向波动，M={m:.2f} 需结合周期位置判断"
        return f"🔍 需复核——M={m:.2f} 偏高，需人工核对 DSRI/TATA 具体驱动"

    # --- OCF/NI：金融/建筑/军工/航空/软件 误报为主
    if rule == "ocf_to_ni_5y":
        if ind in ("银行", "非银金融"):
            return "⚠️ 误报——银行/券商/保险现金流表结构与实业不同，OCF/NI 无意义，应看不良率/拨备覆盖"
        if ind == "建筑装饰":
            return "⚠️ 误报——建筑央企垫资施工，OCF 波动大且常为负，需看应收账款周转"
        if ind == "国防军工":
            return "⚠️ 误报——军品政府订单回款慢，OCF 季节性负值常见，多为误报"
        if ind == "计算机":
            return "⚠️ 误报——软件项目制/预收模式，OCF 与净利错配正常，需看应收"
        if ind == "交通运输":
            return "⚠️ 误报——航空重资产+折旧大，OCF 偏离属正常；需区分真实偿债风险"
        if ind == "农林牧渔":
            return "🔍 需复核——养殖强周期，亏损期 OCF 可为负，需看周期位置"
        if ind in ("公用事业", "房地产"):
            return "🔍 需复核——重资产+行业周期，OCF 波动需看真实现金流"
        return "🔍 需复核——纸面利润风险，需人工核对现金背书（警惕康美式 OCF/NI 长期背离）"

    # --- 股本膨胀：送转/定增 误报为主
    if rule == "share_dilution_5y":
        if ind in ("电子", "计算机", "电力设备", "通信", "医药生物", "机械设备"):
            return "⚠️ 误报——科创板/创业板高送转或定增扩产机械增股本，非真稀释，需区分送转(无实质稀释)与真融资"
        return "🔍 需复核——股本膨胀需区分送转(无实质稀释)与增发募资(真稀释)"

    # --- 杠杆（净负债/EBITDA 或 利息覆盖）
    if rule == "leverage":
        if "净负债" in rule_desc:
            if ind == "非银金融":
                return "⚠️ 误报——金融企业净负债口径不适用（负债是经营资产）"
            if ind in ("房地产", "建筑装饰", "交通运输", "公用事业", "钢铁", "环保"):
                return "⚠️ 误报——重资产高负债是商业模式常态，非破产信号（应已豁免，此处为漏网）"
            return "🔍 需复核——高杠杆需看利息覆盖与现金流，周期下行时才是真雷"
        # 利息覆盖
        if ind == "医药生物":
            return "⚠️ 误报——未盈利 Biotech 研发期利息覆盖为负是常态，非造假"
        return "🔍 需复核——利息覆盖不足需看偿债与再融资能力"

    # --- Altman Z：重资产低杠杆 误报为主
    if rule == "altman_z_score":
        if ind in ("机械设备", "汽车", "有色金属", "钢铁", "基础化工", "电力设备", "建筑材料"):
            return "⚠️ 误报——低杠杆重资产公司 Z 系统性偏低（净现金公司尤甚），非破产信号"
        return "🔍 需复核——Z<1.8 需结合净负债与现金流判断"

    return "🔍 需复核"


def judge(row) -> str:
    code = str(row.get("code", ""))
    if code in CURATED and CURATED[code]:
        return CURATED[code]
    return _heuristic(row.get("industry"), row.get("rule"), row.get("rule_desc", ""), row.get("value"))


def judge_column(rejected: pd.DataFrame) -> pd.Series:
    return rejected.apply(judge, axis=1)


def label(s: str) -> str:
    if s.startswith("✅"):
        return "真雷"
    if s.startswith("⚠️"):
        return "误报"
    return "需复核"


def veto_report_md(rejected: pd.DataFrame) -> str:
    """生成带「复核判断」列的 L3 排雷报告 Markdown（与 cli screen 输出同构）。"""
    from .vetoes import veto_summary  # vi_system.pipeline.vetoes

    if rejected is None or len(rejected) == 0:
        return "# 排雷报告（L3）\n\n无否决记录"

    s = veto_summary(rejected)
    df = rejected.copy()
    df["判断"] = judge_column(df)

    lines = ["# 排雷报告（L3）", "", f"共否决 {len(df)} 只", "",
             "| 规则 | 说明 | 数量 | 占比 |", "|------|------|------|------|"]
    for _, r in s.iterrows():
        lines.append(f"| {r['rule']} | {r['rule_desc']} | {r['n']} | {r['share']:.1%} |")

    lines += ["", "## 明细", "",
              "| 代码 | 名称 | 行业 | 触发 | 实际值 | 阈值 | 复核判断 |",
              "|------|------|------|---------|--------|------|---------|"]
    for _, r in df.iterrows():
        val = r["value"]
        val = f"{val:.3f}" if isinstance(val, float) else str(val)
        lines.append(f"| {r['code']} | {r['name']} | {r['industry']} | {r['rule_desc']} | {val} | {r['threshold']} | {r['判断']} |")

    lines += ["",
              "> ✅ 真雷=否决正确；⚠️ 误报=模型/规则对该类公司的系统性误判；🔍 需复核=无法一刀切，需人工核对。",
              "> 复核判断由领域知识（公司实际情况 + 行业×规则误报规律）给出，仅供人工复核参考，**不改变 L3 一票否决结果**。"]
    return "\n".join(lines)
